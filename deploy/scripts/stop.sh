#!/usr/bin/env bash
# =============================================================================
# SynPharm Docker 环境 - 停止服务（Linux / macOS / WSL）
# =============================================================================
set -euo pipefail
cd "$(dirname "$0")/.."

echo "=========================================="
echo "  SynPharm Docker 环境 - 停止服务"
echo "=========================================="

docker compose down

echo ""
echo "服务已停止。"
echo "数据卷已保留（数据库、Redis、上传文件）。如需彻底清除数据，请执行:"
echo "  docker compose down -v"
echo "=========================================="
